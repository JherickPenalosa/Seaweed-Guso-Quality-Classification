import 'dart:async';
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:http/http.dart' as http;
import 'package:http_parser/http_parser.dart';
import 'package:image_picker/image_picker.dart';

import 'mobile_auth_service.dart';

/// gUSo Mobile classification and history API integration.
///
/// No UI components are implemented or modified here.
///
/// Authentication uses the JWT issued through MobileAuthService.
/// All classification, save, history and delete actions are handled
/// by the existing FastAPI backend and PostgreSQL database.
class MobileClassificationApiService {
  const MobileClassificationApiService();

  static const Duration _normalTimeout = Duration(seconds: 30);
  static const Duration _uploadTimeout = Duration(seconds: 120);

  static String get baseUrl => MobileAuthService.baseUrl;

  static Uri _url(String path) {
    final root = baseUrl.endsWith('/')
        ? baseUrl.substring(0, baseUrl.length - 1)
        : baseUrl;

    return Uri.parse('$root$path');
  }

  /// Use the same JWT created by mobile authentication.
  static Map<String, String> _authHeaders() {
    return {
      ...MobileAuthService.authorizationHeaders,
      'Accept': 'application/json',
    };
  }

  /// Verify that the Android application can reach FastAPI.
  ///
  /// Returns true if the OpenAPI endpoint responds successfully.
  Future<bool> checkConnection() async {
    try {
      final response = await http
          .get(_url('/openapi.json'))
          .timeout(const Duration(seconds: 8));

      return response.statusCode == 200;
    } on TimeoutException {
      return false;
    } on SocketException {
      return false;
    } on http.ClientException {
      return false;
    }
  }

  /// Upload and classify a JPG or PNG image.
  ///
  /// POST /classifications/
  ///
  /// Returns the actual FastAPI response:
  /// {
  ///   "filename": "...",
  ///   "result": {
  ///     "classification_id": ...,
  ///     "quality_grade": ...,
  ///     "confidence": ...
  ///   }
  /// }
  ///
  /// No mocked prediction is generated by this service.
  Future<Map<String, dynamic>> classifyImage({required XFile image}) async {
    if (image.path.trim().isEmpty) {
      throw const MobileAuthException('Please select a valid image.');
    }

    final filename = image.name;
    final extension = filename.toLowerCase();

    late final String mimeType;

    if (extension.endsWith('.jpg') || extension.endsWith('.jpeg')) {
      mimeType = 'image/jpeg';
    } else if (extension.endsWith('.png')) {
      mimeType = 'image/png';
    } else {
      throw const MobileAuthException(
        'Only JPG, JPEG, and PNG images are supported.',
      );
    }

    try {
      final request = http.MultipartRequest('POST', _url('/classifications/'));

      request.headers.addAll(_authHeaders());

      request.files.add(
        await http.MultipartFile.fromPath(
          'file',
          image.path,
          filename: filename,
          contentType: MediaType.parse(mimeType),
        ),
      );

      final streamed = await request.send().timeout(_uploadTimeout);

      final response = await http.Response.fromStream(streamed)
          .timeout(_uploadTimeout);

      final data = _decodeResponse(response, expectedStatus: 200);

      final result = data['result'];

      if (result is! Map) {
        throw const MobileAuthException(
          'FastAPI returned an unexpected classification result.',
        );
      }

      // Do not invent a quality classification if the backend
      // rejected an unsuitable or uncertain image.
      if (result['classification_id'] == null ||
          result['quality_grade'] == null) {
        final message = result['message'];

        throw MobileAuthException(
          message is String && message.isNotEmpty
              ? message
              : 'The image could not be classified.',
        );
      }

      return data;
    } on TimeoutException {
      throw const MobileAuthException(
        'Classification timed out. Please try again.',
      );
    } on SocketException {
      throw const MobileAuthException(
        'Cannot reach the gUSo classification backend.',
      );
    } on http.ClientException {
      throw const MobileAuthException('The image upload connection failed.');
    } on FileSystemException {
      throw const MobileAuthException(
        'The selected image could not be opened.',
      );
    }
  }

  /// Save an existing classification to PostgreSQL.
  ///
  /// POST /classifications/{classification_id}/save
  ///
  /// Only the owner of a classification may save it.
  Future<Map<String, dynamic>> saveClassification({
    required int classificationId,
  }) async {
    _validateId(classificationId);

    try {
      final response = await http
          .post(
            _url('/classifications/$classificationId/save'),
            headers: _authHeaders(),
          )
          .timeout(_normalTimeout);

      return _decodeResponse(response, expectedStatus: 200);
    } on TimeoutException {
      throw const MobileAuthException('Saving timed out. Please try again.');
    } on SocketException {
      throw const MobileAuthException(
        'Cannot connect to FastAPI while saving.',
      );
    } on http.ClientException {
      throw const MobileAuthException('Unable to save the classification.');
    }
  }

  /// Fetch the authenticated user's saved classifications.
  ///
  /// GET /history/me
  ///
  /// Records are retrieved from PostgreSQL, not local sample data.
  Future<List<Map<String, dynamic>>> fetchHistory() async {
    try {
      final response = await http
          .get(_url('/history/me'), headers: _authHeaders())
          .timeout(_normalTimeout);

      final data = _decodeResponse(response, expectedStatus: 200);

      final records = data['records'];

      if (records is! List) {
        throw const MobileAuthException(
          'FastAPI returned an invalid History response.',
        );
      }

      final result = <Map<String, dynamic>>[];

      for (final record in records) {
        if (record is! Map) {
          throw const MobileAuthException(
            'FastAPI returned an invalid History record.',
          );
        }

        result.add(Map<String, dynamic>.from(record));
      }

      return result;
    } on TimeoutException {
      throw const MobileAuthException('Loading History timed out.');
    } on SocketException {
      throw const MobileAuthException(
        'Cannot connect to FastAPI while loading History.',
      );
    } on http.ClientException {
      throw const MobileAuthException(
        'Unable to retrieve classification History.',
      );
    }
  }

  /// Download a saved classification's original image.
  ///
  /// GET /history/{classification_id}/image
  ///
  /// Returns bytes suitable for Image.memory().
  Future<Uint8List> fetchSavedImage({required int classificationId}) async {
    _validateId(classificationId);

    try {
      final response = await http
          .get(
            _url('/history/$classificationId/image'),
            headers: _authHeaders(),
          )
          .timeout(_normalTimeout);

      if (response.statusCode == 401) {
        const MobileAuthService().logout();

        throw const MobileAuthException(
          'Your session has expired. Please log in again.',
          statusCode: 401,
        );
      }

      if (response.statusCode != 200) {
        throw MobileAuthException(
          _errorMessage(response.body, 'Unable to retrieve the saved image.'),
          statusCode: response.statusCode,
        );
      }

      return response.bodyBytes;
    } on TimeoutException {
      throw const MobileAuthException('Loading the saved image timed out.');
    } on SocketException {
      throw const MobileAuthException(
        'Cannot connect to FastAPI to retrieve the image.',
      );
    } on http.ClientException {
      throw const MobileAuthException('Unable to retrieve the saved image.');
    }
  }

  /// Permanently delete an owned, saved classification.
  ///
  /// DELETE /classifications/{classification_id}
  Future<Map<String, dynamic>> deleteSavedClassification({
    required int classificationId,
  }) async {
    _validateId(classificationId);

    try {
      final response = await http
          .delete(
            _url('/classifications/$classificationId'),
            headers: _authHeaders(),
          )
          .timeout(_normalTimeout);

      return _decodeResponse(response, expectedStatus: 200);
    } on TimeoutException {
      throw const MobileAuthException('Deleting the classification timed out.');
    } on SocketException {
      throw const MobileAuthException(
        'Cannot connect to FastAPI while deleting.',
      );
    } on http.ClientException {
      throw const MobileAuthException('Unable to delete the classification.');
    }
  }

  /// Handle FastAPI responses and authentication errors.
  static Map<String, dynamic> _decodeResponse(
    http.Response response, {
    required int expectedStatus,
  }) {
    if (response.statusCode == 401) {
      const MobileAuthService().logout();

      throw const MobileAuthException(
        'Your session has expired. Please log in again.',
        statusCode: 401,
      );
    }

    late final dynamic decoded;

    try {
      decoded = jsonDecode(response.body);
    } on FormatException {
      throw MobileAuthException(
        'FastAPI returned an invalid response.',
        statusCode: response.statusCode,
      );
    }

    if (response.statusCode == expectedStatus && decoded is Map) {
      return Map<String, dynamic>.from(decoded);
    }

    if (decoded is Map) {
      final detail = decoded['detail'];

      if (detail is String && detail.trim().isNotEmpty) {
        throw MobileAuthException(detail, statusCode: response.statusCode);
      }

      if (detail is List && detail.isNotEmpty) {
        final first = detail.first;

        if (first is Map && first['msg'] is String) {
          throw MobileAuthException(
            first['msg'] as String,
            statusCode: response.statusCode,
          );
        }
      }
    }

    throw MobileAuthException(
      'FastAPI request failed (HTTP ${response.statusCode}).',
      statusCode: response.statusCode,
    );
  }

  static String _errorMessage(String body, String fallback) {
    try {
      final decoded = jsonDecode(body);

      if (decoded is Map && decoded['detail'] is String) {
        return decoded['detail'] as String;
      }
    } on FormatException {
      return fallback;
    }

    return fallback;
  }

  static void _validateId(int id) {
    if (id <= 0) {
      throw const MobileAuthException('Invalid classification ID.');
    }
  }
}
